-- =============================================================================
-- 03_roles_and_access.sql
-- A minimal role separation so the project reads like real warehouse governance,
-- not everything running as ACCOUNTADMIN. Optional on a solo trial account but
-- worth including — it's one of the first things a reviewer checks for.
-- =============================================================================

USE ROLE SECURITYADMIN;

CREATE ROLE IF NOT EXISTS NG_FLOOD_LOADER   COMMENT = 'Writes to RAW and STAGING via ingestion scripts';
CREATE ROLE IF NOT EXISTS NG_FLOOD_TRANSFORMER COMMENT = 'Builds CORE and MARTS from STAGING (Snowpark jobs)';
CREATE ROLE IF NOT EXISTS NG_FLOOD_READER   COMMENT = 'Read-only access to MARTS for the Streamlit app / BI';

GRANT ROLE NG_FLOOD_LOADER TO ROLE SYSADMIN;
GRANT ROLE NG_FLOOD_TRANSFORMER TO ROLE SYSADMIN;
GRANT ROLE NG_FLOOD_READER TO ROLE SYSADMIN;

USE ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE NG_FLOOD_WH TO ROLE NG_FLOOD_LOADER;
GRANT USAGE ON WAREHOUSE NG_FLOOD_WH TO ROLE NG_FLOOD_TRANSFORMER;
GRANT USAGE ON WAREHOUSE NG_FLOOD_WH TO ROLE NG_FLOOD_READER;

GRANT USAGE ON DATABASE NG_FLOOD_RISK TO ROLE NG_FLOOD_LOADER;
GRANT USAGE ON DATABASE NG_FLOOD_RISK TO ROLE NG_FLOOD_TRANSFORMER;
GRANT USAGE ON DATABASE NG_FLOOD_RISK TO ROLE NG_FLOOD_READER;

GRANT USAGE, CREATE TABLE ON SCHEMA NG_FLOOD_RISK.RAW TO ROLE NG_FLOOD_LOADER;
GRANT USAGE, CREATE TABLE ON SCHEMA NG_FLOOD_RISK.STAGING TO ROLE NG_FLOOD_LOADER;

GRANT USAGE ON SCHEMA NG_FLOOD_RISK.STAGING TO ROLE NG_FLOOD_TRANSFORMER;
GRANT SELECT ON ALL TABLES IN SCHEMA NG_FLOOD_RISK.STAGING TO ROLE NG_FLOOD_TRANSFORMER;
GRANT USAGE, CREATE TABLE ON SCHEMA NG_FLOOD_RISK.CORE TO ROLE NG_FLOOD_TRANSFORMER;
GRANT USAGE, CREATE TABLE ON SCHEMA NG_FLOOD_RISK.MARTS TO ROLE NG_FLOOD_TRANSFORMER;

GRANT USAGE ON SCHEMA NG_FLOOD_RISK.MARTS TO ROLE NG_FLOOD_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA NG_FLOOD_RISK.MARTS TO ROLE NG_FLOOD_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA NG_FLOOD_RISK.MARTS TO ROLE NG_FLOOD_READER;

